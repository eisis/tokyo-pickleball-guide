export type Origin = { name: string; lat: number; lng: number; here?: boolean };

/** 2地点の直線距離（km） */
export function km(a: { lat: number; lng: number }, b: { lat: number; lng: number }) {
  const r = Math.PI / 180;
  const dLat = (b.lat - a.lat) * r;
  const dLng = (b.lng - a.lng) * r;
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(a.lat * r) * Math.cos(b.lat * r) * Math.sin(dLng / 2) ** 2;
  return 12742 * Math.asin(Math.sqrt(h));
}

/** 入力された文字から地名を探す（「豊洲駅」「船橋市」「みなと」なども拾う）。見つからなければ null */
export function findPlace(input: string, courtAreas: { name: string; lat: number; lng: number }[] = []): Origin | null {
  const k = input.trim().replace(/(駅|周辺|付近|近く|エリア|町|市|区)$/, '');
  if (!k) return null;
  if (PLACES[k]) return { name: k, lat: PLACES[k][0], lng: PLACES[k][1] };
  const area = courtAreas.find((a) => a.name === k || a.name.split('・').includes(k));
  if (area) return { name: k, lat: area.lat, lng: area.lng };
  if (k.length >= 2) {
    const p = Object.keys(PLACES).find((name) => name.startsWith(k));
    if (p) return { name: p, lat: PLACES[p][0], lng: PLACES[p][1] };
  }
  return null;
}
